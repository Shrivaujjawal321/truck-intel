"""Mapbox Vector Tiles for the local data viewer.

One endpoint, one layer registry. Every layer is a real core/osm table — the
tile is generated by PostGIS (`ST_AsMVT`), so 450k route rows render without
the API ever materialising them as JSON.

Two rules this file inherits from the rest of the API:
- read-only session (`common.connect_ro`), so a viewer can never mutate data;
- the route network is the *truck-designated* network only (`core.truck_routes`,
  NTAD National Network). `osm.ways` is deliberately NOT a layer here: it is the
  generic road graph and must never be shown as a truck route.
"""
from __future__ import annotations

from dataclasses import dataclass, field

import psycopg
from fastapi import APIRouter, Path
from fastapi.responses import Response

from api import common

router = APIRouter(tags=["viewer"])

MVT_EXTENT = 4096
MVT_BUFFER = 64
# ST_TileEnvelope margin, in tile fractions: pull in features just outside the
# tile so lines and symbols do not get clipped at the seam.
TILE_MARGIN = 0.0625
# Density-grid resolution at low zoom: cells across one tile edge. 64 => at most
# 4,096 features per tile regardless of how many rows fall inside it.
CLUSTER_CELLS = 64
# Below this zoom, point layers are drawn as a density grid instead of as
# individual rows. Above it, every row in view is drawn.
POINT_CLUSTER_ZOOM = 8

# Gate 6 (truckintel.liveness) on the map: keep a place off the map only when a
# source POSITIVELY asserted it closed. Deliberately NOT `liveness >= n`:
#
#   'closed'         a source said so         -> hide. This is an assertion.
#   'likely_closed'  scored under 25          -> SHOW, badged. This is a score.
#   'unknown'        old data, nothing current-> SHOW, badged.
#   NULL             never scored             -> SHOW. Unscored is not closed,
#                                               and IS DISTINCT FROM keeps it.
#
# Hiding low scores would turn "nobody has confirmed this since 2019" into
# "this is gone", which is the inference liveness.py exists to refuse. The
# driver at 2 a.m. is better served by a badged maybe than by an empty map.
LIVE_FILTER = "live_state IS DISTINCT FROM 'closed'"


@dataclass(frozen=True)
class Layer:
    """One map layer: where it lives, what a click should show, how dense it is."""

    table: str
    id_col: str
    props: tuple[str, ...]
    kind: str  # "line" | "point" — drives the viewer's style
    min_zoom: int  # below this, the viewer does not request tiles at all
    max_features: int  # per-tile guard; the viewer reports when it bites
    label: str
    color: str
    order_by: str | None = None  # optional: which rows survive the LIMIT first
    # Optional SQL predicate that decides which rows are ON the map at all, e.g.
    # "on_route_5km". A filtered layer is a DIFFERENT count from its table, so
    # /v1/viewer/inventory reports rows_mapped AND rows_total side by side —
    # a map showing fewer dots than the table holds must always be visible as a
    # number, never discovered by eye.
    row_filter: str | None = None
    # Generalized stand-in used below `gen_below_zoom`, so a low-zoom tile shows
    # the WHOLE layer at lower detail instead of a LIMIT-truncated slice of it.
    gen_table: str | None = None
    gen_below_zoom: int = 0
    # Point layers below this zoom are served as a density grid (one feature per
    # cell, carrying `n`). Every row is still counted — nothing is dropped, the
    # unit of display just changes from "a station" to "how many stations here".
    cluster_below_zoom: int = 0
    # Drawn on first load? The dense layers start off: 629k bridge markers on top
    # of everything else is not "seeing your data", it is hiding it. One click on.
    default_on: bool = True
    flags: tuple[str, ...] = field(default=())

    def source_for(self, z: int) -> tuple[str, bool]:
        """(table, is_generalized) for this zoom."""
        if self.gen_table and z < self.gen_below_zoom:
            return self.gen_table, True
        return self.table, False

    def clustered_at(self, z: int) -> bool:
        return self.kind == "point" and z < self.cluster_below_zoom


