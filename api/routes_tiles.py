# Columns the generalized route table does not carry. They stay in the tile
# schema as NULL so a popup renders them as "unknown" rather than vanishing.
_GEN_ABSENT: dict[str, frozenset[str]] = {
    "core.truck_routes_gen": frozenset({"fclass", "through_lanes"}),
}

# A generalized stand-in table is a different table, and there is no guarantee it
# carries the filter column. Silently dropping the predicate at low zoom would
# show rows the layer promises to exclude, so the combination is banned outright
# rather than special-cased.
for _name, _spec in LAYERS.items():
    if _spec.row_filter and _spec.gen_table:
        raise AssertionError(
            f"layer '{_name}' sets both row_filter and gen_table; the filter "
            f"would be unenforceable below zoom {_spec.gen_below_zoom}"
        )


def _filter_clause(layer: Layer, alias: str = "t") -> str:
    """`AND <predicate>` for a filtered layer, or '' — safe to concatenate.

    The predicate is developer-authored code in this module's registry, never
    request input, so it is interpolated rather than parameterised. Column
    references are alias-qualified so the clause is valid in either query shape.
    """
    if not layer.row_filter:
        return ""
    return f" AND {alias}.{layer.row_filter}"


def _cluster_sql(layer: Layer, z: int) -> str:
    """Density grid for a point layer at low zoom.

    Rows are snapped to a grid whose cell is 1/CLUSTER_CELLS of the tile, so a
    tile carries at most CLUSTER_CELLS^2 features no matter how dense the data
    is — bounded work, and `n` accounts for every row in the cell.
    """
    return f"""
        WITH b AS (
            SELECT ST_TileEnvelope(%(z)s, %(x)s, %(y)s) AS tile,
                   ST_Transform(
                       ST_TileEnvelope(%(z)s, %(x)s, %(y)s, margin => {TILE_MARGIN}),
                       4326
                   ) AS lookup
        ),
        cells AS (
            -- Grouped BY the grid, but placed at the mean position of the rows in
            -- the cell. Snapping the marker to the grid instead draws a visible
            -- lattice across the country — an artifact of the cell size, not of
            -- where anything actually is.
            SELECT ST_Centroid(ST_Collect(t.geom)) AS cell, count(*)::int AS n
            FROM {layer.table} t, b
            WHERE t.geom && b.lookup{_filter_clause(layer)}
            GROUP BY ST_SnapToGrid(t.geom, %(cell)s)
        ),
        mvt AS (
            SELECT ST_AsMVTGeom(
                       ST_Transform(cells.cell, 3857), b.tile,
                       {MVT_EXTENT}, {MVT_BUFFER}, true
                   ) AS geom,
                   cells.n
            FROM cells, b
        )
        SELECT ST_AsMVT(mvt, %(layer)s, {MVT_EXTENT}, 'geom') AS tile FROM mvt
    """


def _tile_sql(layer: Layer, z: int) -> str:
    """MVT for one tile.

    The bbox filter runs against the stored 4326 geometry so the GIST index is
    usable; only the surviving rows are reprojected to 3857 for ST_AsMVTGeom.
    """
    table, generalized = layer.source_for(z)
    absent = _GEN_ABSENT.get(table, frozenset())
    prop_cols = ", ".join(
        f"NULL AS {c}" if c in absent else f"t.{c}" for c in layer.props
    )
    order_by = layer.order_by
    if order_by and order_by.split()[0] in absent:
        order_by = None
    order_clause = f"ORDER BY t.{order_by}" if order_by else ""
    return f"""
        WITH b AS (
            SELECT ST_TileEnvelope(%(z)s, %(x)s, %(y)s) AS tile,
                   ST_Transform(
                       ST_TileEnvelope(%(z)s, %(x)s, %(y)s, margin => {TILE_MARGIN}),
                       4326
                   ) AS lookup
        ),
        src AS (
            SELECT t.{layer.id_col}::text AS feature_id, {prop_cols}, t.geom
            FROM {table} t, b
            WHERE t.geom && b.lookup{_filter_clause(layer)}
            {order_clause}
            LIMIT %(limit)s
        ),
        mvt AS (
            SELECT ST_AsMVTGeom(
                       ST_Transform(src.geom, 3857), b.tile,
                       {MVT_EXTENT}, {MVT_BUFFER}, true
                   ) AS geom,
                   src.feature_id, {", ".join(f"src.{c}" for c in layer.props)}
            FROM src, b
        )
        SELECT ST_AsMVT(mvt, %(layer)s, {MVT_EXTENT}, 'geom') AS tile FROM mvt
    """


@router.get("/v1/tiles/{layer}/{z}/{x}/{y}.mvt")
def tile(
    layer: str,
    z: int = Path(ge=0, le=22),
    x: int = Path(ge=0),
    y: int = Path(ge=0),
) -> Response:
    """One vector tile. 204 when the tile is empty — MapLibre treats it as blank."""
    spec = LAYERS.get(layer)
    if spec is None:
        raise common.ApiError(
            "not_found",
            f"unknown layer '{layer}'; known: {', '.join(sorted(LAYERS))}",
            status=404,
        )
    span = 1 << z
    if x >= span or y >= span:
        raise common.ApiError("invalid_param", f"x/y out of range for zoom {z}")

    table, generalized = spec.source_for(z)
    clustered = spec.clustered_at(z)
    params = {"z": z, "x": x, "y": y, "limit": spec.max_features, "layer": layer}
    if clustered:
        # Tile spans 360/2^z degrees of longitude; CLUSTER_CELLS cells across it.
        params["cell"] = (360.0 / (1 << z)) / CLUSTER_CELLS
        sql = _cluster_sql(spec, z)
    else:
        sql = _tile_sql(spec, z)

    try:
        with common.connect_ro() as conn:
            row = conn.execute(sql, params).fetchone()
    except psycopg.Error as exc:
        raise common.ApiError(
            "upstream_unavailable",
            f"database unavailable ({type(exc).__name__})",
            status=503,
        ) from exc

    blob = bytes(row["tile"]) if row and row["tile"] is not None else b""
    if not blob:
        return Response(status_code=204)
    return Response(
        content=blob,
        media_type="application/vnd.mapbox-vector-tile",
        headers={
            "Cache-Control": "public, max-age=300",
            # Which table this tile actually came from — so "what am I looking at"
            # is answerable from the wire, not from reading this file.
            "X-Source-Table": table,
            "X-Generalized": "true" if generalized else "false",
            "X-Clustered": "true" if clustered else "false",
        },
    )


